"use strict";
const assert=require("node:assert/strict"),path=require("node:path"),{chromium}=require("playwright");
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  for(const width of [1440,390,320]){
   const page=await browser.newPage({viewport:{width,height:900}});
   const errors=[];page.on("pageerror",e=>errors.push(e.message));
   await page.goto("file://"+path.resolve(__dirname,"index.html"));
   await page.waitForFunction(()=>document.querySelector("#debt-proceeds").textContent.startsWith("$"));
   assert.equal(errors.length,0,errors.join("; "));
   assert.equal(await page.locator("#debt-proceeds").innerText(),"$4,691,080");
   assert.equal(await page.locator("#binding-note").innerText(),"Binding test: DSCR");
   assert.equal(await page.locator("#sensitivity-table tr").count(),5);
   assert.equal(await page.locator("#sensitivity-chart .uplot").count(),1);
   const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
   assert.equal(overflow,false,"Horizontal overflow at "+width);
   await page.getByRole("button",{name:/Loan & Balloon/}).click();
   assert.equal(await page.locator("#panel-loan").isVisible(),true);
   assert.equal(await page.locator("#loan-year-table tr").count(),11);
   assert.equal(await page.locator("#amort-chart .uplot").count(),1);
   assert.match(await page.locator("#loan-monthly").innerText(),/^\\$/);
   const initialBalloon=await page.locator("#loan-balloon").innerText();
   assert.notEqual(initialBalloon,"—");
   await page.locator("#loan-io").check();
   assert.equal(await page.locator("#loan-balloon").innerText(),"$4,691,080");
   await page.locator("#loan-mode").selectOption("custom");
   await page.locator("#loan-amount").fill("1000000");
   assert.equal(await page.locator("#loan-balloon").innerText(),"$1,000,000");
   await page.locator("#loan-io").uncheck();
   assert.notEqual(await page.locator("#loan-balloon").innerText(),"$1,000,000");
   await page.locator("#loan-mode").selectOption("modeled");
   await page.getByRole("button",{name:/Capital Structure/}).click();
   assert.equal(await page.locator("#panel-capital").isVisible(),true);
   assert.equal(await page.locator("#capital-uses").innerText(),"$5,790,000");
   assert.equal(await page.locator("#capital-gap").innerText(),"$248,920");
   assert.equal(await page.locator("#capital-stack-table tr").count(),4);
   await page.locator("#capital-sponsor").fill("600000");
   assert.equal(await page.locator("#capital-gap").innerText(),"$0");
   assert.equal(await page.locator("#capital-stack-table tr").count(),4);
   await page.locator("#capital-type").selectOption("preferred-equity");
   assert.match(await page.locator("#capital-disclosure").innerText(),/not a lender DSCR/);
   await page.locator("#capital-sponsor").fill("350000");
   await page.locator("#capital-rate").fill("101");
   assert.equal(await page.locator("#capital-error").isVisible(),true);
   await page.locator("#capital-rate").fill("12");
   assert.equal(await page.locator("#capital-error").isVisible(),false);
   await page.getByRole("button",{name:/Refinance Intelligence/}).click();
   assert.equal(await page.locator("#ref-gap").innerText(),"$1,088,920");
   assert.equal(await page.locator("#ref-uses").innerText(),"$5,780,000");
   await page.locator("#noi").fill("572000");
   assert.equal(await page.locator("#debt-proceeds").innerText(),"$5,160,188");
   assert.equal(await page.locator("#binding-note").innerText(),"Binding test: DSCR");
   assert.equal(await page.locator("#sensitivity-table tr").count(),5);
   await page.getByRole("button",{name:/Scenario Lab/}).click();
   assert.equal(await page.locator("#scenario-table tr").count(),3);
   await page.getByRole("button",{name:/Analysis Report/}).click();
   assert.equal(await page.locator("#report-inputs tr").count(),10);
   await page.locator("#value").fill("-1");
   assert.equal(await page.locator("#error").isVisible(),true);
   await page.getByRole("button",{name:"Reset example"}).click();
   assert.equal(await page.locator("#error").isVisible(),false);
   assert.equal(await page.locator("#report-loan").innerText(),"$4,691,080");
   console.log("Desk browser smoke passed at",width);
   await page.close();
  }
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});